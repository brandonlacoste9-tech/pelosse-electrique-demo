let lang = localStorage.getItem("pelosse-lang") || "fr";

function applyLang(l) {
  lang = l;
  localStorage.setItem("pelosse-lang", l);
  document.documentElement.lang = l;
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    const val = I18N[l][key];
    if (val !== undefined) el.innerHTML = val;
  });
  document.getElementById("langToggle").textContent = l === "fr" ? "EN" : "FR";
  document.title = l === "fr"
    ? "Les Entreprises J.F. Pelosse & Fils — Électricien à Saint-Jean-sur-Richelieu | Installation, dépannage"
    : "J.F. Pelosse & Fils — Electrician in Saint-Jean-sur-Richelieu | Installation, troubleshooting";
}

document.getElementById("langToggle").addEventListener("click", () => applyLang(lang === "fr" ? "en" : "fr"));

